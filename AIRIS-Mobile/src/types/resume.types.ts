/**
 * Deterministically determines if an analysis record conforms to the v3 canonical model.
 * A record is canonical if scoringModelVersion is explicitly "3.0.0-canonical",
 * or if it contains valid resumeScore and alignmentScore payloads without legacy version markers.
 */
export function isCanonicalRecord(analysis: any): boolean {
  if (!analysis) return false;
  if (analysis.scoringModelVersion === "3.0.0-canonical") return true;
  if (analysis.analysisVersion === "3.0.0-canonical") return true;
  if (analysis.atsScore?.traceability?.scoringModelVersion === "3.0.0-canonical") return true;
  if (analysis.scoringModelVersion && (analysis.scoringModelVersion.startsWith("1.") || analysis.scoringModelVersion.startsWith("2."))) {
    return false;
  }
  return Boolean(
    analysis.resumeScore?.overallScore !== undefined &&
    analysis.alignmentScore?.overallScore !== undefined &&
    analysis.atsScore?.overallScore !== undefined
  );
}

/**
 * Determines if an analysis record was generated by a legacy model (pre-v3).
 */
export function isLegacyRecord(analysis: any): boolean {
  if (!analysis) return false;
  return !isCanonicalRecord(analysis);
}

